#!/usr/bin/env python3
"""Per-frame sound effects on channel 2, written as editable lists -> src/sfx_tables.c + include/sfx_tables.h.
Never edit the generated files by hand; change the lists here and rerun.

An effect is a pulse duty (12, 25, 50 or 75 %) and one entry per frame (60 a second). An entry is a pitch in Hz,
or (Hz, 'vV') / (Hz, 'vV+P') / (Hz, 'vV-P'): retrigger the note at volume V (0-15) with the hardware envelope
rising or falling one step every P/64 s (no sign: constant volume). The first entry must retrigger. After the
last entry the note keeps its pitch and envelope, so every effect ends on a fall ('-1' is the fastest, about a
step a frame): cutting the channel instead drops the pulse's DC level at once and thumps. Pitches between
retriggers glide without restarting the note.

The pitches and levels were measured frame by frame from the original's effects (tools/sfx_page.py lists the
events): the collect/jump sounds are short pitch glides, the power-up is a wind-up followed by rising whoops; the eat sound is a downward gulp with an echo; the power
warning is a triple beep. The beeps' gaps are a 'v0' retrigger on a 12.5 % pulse, whose small DC step does not thump.

usage: sfx_tables.py
"""
