DUTY = {12: 0x00, 25: 0x40, 50: 0x80, 75: 0xC0}
# Every volume above is scaled by GAIN so the effects sit under the melody: the lead (CH1) is a 12.5 % pulse at 15,
# RMS ~0.33 x 15 = 5; a 50 % pickup at 11 was 0.5 x 11 = 5.5, louder than the tune. 0.7 is -3 dB.
GAIN = 0.7

def gb_x(hz):
    x = round(2048 - 131072 / hz)
    assert 0 <= x < 2048, hz
    return x

def env(code):
    m = re.fullmatch(r'v(\d+)(?:([+-])(\d))?', code)
    assert m, code
    v = int(m[1]); assert 0 <= v <= 15, code
    v = max(1, round(v * GAIN)) if v else 0
    pace = int(m[3] or 0); up = m[2] == '+'
    e = (v << 4) | (0x08 if up else 0) | pace
    return e if e else 0x08            # NR22 = 0 would switch the DAC off; 0x08 is silent but keeps it on

def build():
    names = list(EFFECTS)
    c = ['/* generated by tools/sfx_tables.py - do not edit */', '#pragma bank 1', '#include "sfx_tables.h"', '']
    for n in names:
        duty, steps = EFFECTS[n]
        assert isinstance(steps[0], tuple), n + ': the first frame must retrigger'
        assert len(steps) < 256, n
        rows = []
        for s in steps:
            hz, e = (s[0], env(s[1])) if isinstance(s, tuple) else (s, 0)
            rows.append('{%d,0x%02X}' % (gb_x(hz), e))
        c.append('static const sfx_step_t %s_steps[] = {' % n)
        for i in range(0, len(rows), 10): c.append('    ' + ', '.join(rows[i:i + 10]) + ',')
        c.append('};')
    c.append('const sfx_prog_t sfx_progs[] = {')
    for n in names:
        duty, steps = EFFECTS[n]
        c.append('    {0x%02X, %d, %s_steps},' % (DUTY[duty], len(steps), n))
    c.append('};')
    h = ['/* generated by tools/sfx_tables.py - do not edit */', '#ifndef SFX_TABLES_H', '#define SFX_TABLES_H',
         '#include <stdint.h>',
         'typedef struct { uint16_t x; uint8_t env; } sfx_step_t;   /* env: NR22 with a retrigger, 0 = glide */',
         'typedef struct { uint8_t duty; uint8_t len; const sfx_step_t *steps; } sfx_prog_t;',
         'enum { ' + ', '.join('SFX_' + n.upper() for n in names) + ' };',
         'extern const sfx_prog_t sfx_progs[];', '#endif']
    root = os.path.join(os.path.dirname(__file__), '..')
    open(os.path.join(root, 'src', 'sfx_tables.c'), 'w').write('\n'.join(c) + '\n')
    open(os.path.join(root, 'include', 'sfx_tables.h'), 'w').write('\n'.join(h) + '\n')
    print('wrote src/sfx_tables.c (%s)' % ', '.join('%s %d frames' % (n, len(EFFECTS[n][1])) for n in names))

if __name__ == '__main__':
    build()
